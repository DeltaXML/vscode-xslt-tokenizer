import * as vscode from 'vscode';
import * as fs from 'fs';
import * as path from 'path';

// The command that deletes the files XSpec tests leave in the workspace (see XSpecRunner.files) - with the HTML reports,
// or keeping them. Only a file named as a run names it, in an xspec folder beside the XSpec file it's for, e.g.
// xspec/order-report-compiled.xsl for order-report.xspec - not, e.g., the XSpec files themselves, which may be in a
// folder named xspec too. An xspec folder left empty is deleted
export class XSpecCleanup {
	public static readonly command = 'xslt-xpath.xspecDeleteGeneratedFiles';
	private static readonly suffixes = ['-compiled.xsl', '-result.xml', '-result.html', '-diffs.json', '-sch-preprocessed.xsl', '-sch-preprocessed.xspec'];

	// the generated files in the folders: by the XSpec file's name, which a suffix follows - e.g. a-sch-preprocessed.xsl,
	// for a.xspec, isn't a-sch's -preprocessed file
	public static generatedFiles(files: string[], keepReports: boolean): string[] {
		return files.filter((file) => {
			if (path.basename(path.dirname(file)) !== 'xspec') {
				return false;
			}
			const name = path.basename(file);
			return XSpecCleanup.suffixes.some((suffix) => name.endsWith(suffix) && !(keepReports && suffix === '-result.html') &&
				fs.existsSync(path.join(path.dirname(path.dirname(file)), name.substring(0, name.length - suffix.length) + '.xspec')));
		});
	}

	public static async run() {
		const found = await vscode.workspace.findFiles(`**/xspec/*{${XSpecCleanup.suffixes.join(',')}}`, '**/node_modules/**');
		const all = XSpecCleanup.generatedFiles(found.filter((uri) => uri.scheme === 'file').map((uri) => uri.fsPath), false);
		if (all.length === 0) {
			vscode.window.showInformationMessage('XSpec: there are no generated files to delete.');
			return;
		}
		const reports = all.filter((file) => file.endsWith('-result.html')).length;
		const deleteAll = 'Delete All';
		const keepReports = 'Keep Reports';
		const choice = await vscode.window.showWarningMessage(`XSpec: delete the ${all.length} files generated by running the tests - ${reports} of them reports?`,
			{ modal: true, detail: 'The test runners, results and reports in the xspec folders beside the XSpec files. Running the tests again makes them again.' },
			deleteAll, ...(reports > 0 && reports < all.length ? [keepReports] : []));
		if (!choice) {
			return;
		}
		const files = choice === keepReports ? all.filter((file) => !file.endsWith('-result.html')) : all;
		const folders = new Set<string>();
		for (const file of files) {
			try {
				fs.rmSync(file);
				folders.add(path.dirname(file));
			} catch {
				// e.g. deleted already
			}
		}
		// the xspec folders left empty
		let foldersDeleted = 0;
		for (const folder of folders) {
			try {
				if (fs.readdirSync(folder).length === 0) {
					fs.rmdirSync(folder);
					foldersDeleted++;
				}
			} catch {
				// e.g. not empty
			}
		}
		vscode.window.showInformationMessage(`XSpec: deleted ${files.length} generated files${foldersDeleted > 0 ? `, and ${foldersDeleted} empty xspec folder${foldersDeleted === 1 ? '' : 's'}` : ''}.`);
	}
}
