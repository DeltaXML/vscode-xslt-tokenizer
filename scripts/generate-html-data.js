/**
 * Generates src/htmlData.ts - the HTML elements, attributes and attribute values for literal result element completion
 * in XSLT (see src/htmlCompletions.ts) - from the HTML data of @vscode/web-custom-data (MIT licence, Microsoft), the data
 * VS Code's own HTML support uses.
 *
 * Usage: npm pack @vscode/web-custom-data, extract it, then
 *   node scripts/generate-html-data.js <path to package/data/browsers.html-data.json>
 *
 * Left out: the event handler attributes (on*), elements without a baseline that aren't widely used, and obsolete ones.
 */
const fs = require('fs');
const path = require('path');

const source = process.argv[2];
if (!source) {
	console.error('usage: node scripts/generate-html-data.js <browsers.html-data.json>');
	process.exit(1);
}
const data = JSON.parse(fs.readFileSync(source, 'utf8'));
const packageJson = JSON.parse(fs.readFileSync(path.join(path.dirname(source), '..', 'package.json'), 'utf8'));

const leftOutElements = new Set(['rb', 'param', 'fencedframe', 'selectedcontent']);
const text = (description) => typeof description === 'string' ? description : description?.value;
const mdn = (item) => item.references?.find((r) => r.name === 'MDN Reference')?.url;
const attribute = (a) => {
	const result = { name: a.name };
	if (a.valueSet) {
		result.valueSet = a.valueSet;
	}
	const description = text(a.description);
	if (description) {
		result.description = description;
	}
	return result;
};

const elements = data.tags.filter((t) => !leftOutElements.has(t.name)).map((t) => {
	const result = { name: t.name, description: text(t.description) ?? '' };
	if (t.void) {
		result.void = true;
	}
	const url = mdn(t);
	if (url) {
		result.mdn = url;
	}
	result.attributes = (t.attributes ?? []).filter((a) => !a.name.startsWith('on')).map(attribute);
	return result;
});
const globalAttributes = data.globalAttributes.filter((a) => !a.name.startsWith('on') && !a.name.startsWith('aria-')).map(attribute);
const used = new Set([...elements.flatMap((e) => e.attributes), ...globalAttributes].map((a) => a.valueSet).filter((v) => v));
const valueSets = {};
data.valueSets.filter((v) => used.has(v.name)).forEach((v) => valueSets[v.name] = v.values.map((value) => value.name));

const out = `// Generated by scripts/generate-html-data.js from @vscode/web-custom-data ${packageJson.version} - do not edit.
// The HTML data is from https://github.com/microsoft/vscode-custom-data - MIT License, Copyright (c) Microsoft Corporation;
// see ThirdPartyNotices.txt.

export interface HtmlAttribute { name: string, valueSet?: string, description?: string }
export interface HtmlElement { name: string, description: string, void?: boolean, mdn?: string, attributes: HtmlAttribute[] }

export const htmlElements: HtmlElement[] = ${JSON.stringify(elements, null, '\t')};

export const htmlGlobalAttributes: HtmlAttribute[] = ${JSON.stringify(globalAttributes, null, '\t')};

// a valueSet without values, 'v', is a boolean attribute: its name is its value
export const htmlValueSets: Record<string, string[]> = ${JSON.stringify(valueSets, null, '\t')};
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'htmlData.ts'), out);
console.log(`src/htmlData.ts: ${elements.length} elements, ${globalAttributes.length} global attributes, ${Object.keys(valueSets).length} value sets, ${Math.round(out.length / 1024)} KB`);
